export function formatById(id: string): OmikujiFormat {
  return FORMATS.find((format) => format.id === id) ?? FORMATS[0];
}

/** 文字列シードから決定的な RNG を作る（xmur3 + mulberry32）。 */
export function seededRng(seed: string): () => number {
  let h = 1779033703 ^ seed.length;
  for (let i = 0; i < seed.length; i++) {
    h = Math.imul(h ^ seed.charCodeAt(i), 3432918353);
    h = (h << 13) | (h >>> 19);
  }
  let a = h >>> 0;
  return () => {
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

function weightedIndex(rng: () => number, weights: readonly number[]): number {
  const total = weights.reduce((sum, w) => sum + w, 0);
  let rest = rng() * total;
  for (let i = 0; i < weights.length; i++) {
    rest -= weights[i];
    if (rest < 0) return i;
  }
  return weights.length - 1;
}

/** 保存される抽選結果一式（文面はインデックスで固定する）。 */
export interface OmikujiRecord {
  format: string;
  number: number;
  rank: OmikujiRank;
  wakaIndex: number;
  summaryIndex: number;
  itemIndices: number[];
}

/** 文面まで解決した抽選結果。 */
export interface OmikujiFortune extends OmikujiRecord {
  formatName: string;
  waka: readonly [string, string];
  summary: string;
  items: { name: OmikujiItem; text: string }[];
}

/** RNG から1回分を抽選する（フォーマット→運勢→番号→文面の順）。 */
export function drawRecord(rng: () => number): OmikujiRecord {
  const format = FORMATS[weightedIndex(rng, FORMATS.map((f) => f.weight))];
  const rank = RANKS[weightedIndex(rng, format.rankWeights)];
  const number = 1 + Math.floor(rng() * 100);
  const wakaIndex = Math.floor(rng() * 3);
  const summaryIndex = Math.floor(rng() * 3);
  const itemIndices = ITEMS.map(() => Math.floor(rng() * 3));
  return { format: format.id, number, rank, wakaIndex, summaryIndex, itemIndices };
}

/** 記録（インデックス群）から文面を解決する。保存済み結果の再表示用。 */
export function fortuneFromRecord(record: OmikujiRecord): OmikujiFortune {
  const format = formatById(record.format);
  const rank = RANKS.includes(record.rank) ? record.rank : "吉";
  const waka = WAKA[rank][record.wakaIndex % 3];
  const summary = SUMMARIES[rank][record.summaryIndex % 3];
  const items = ITEMS.map((name, i) => ({
    name,
    text: ITEM_TEXTS[rank][name][(record.itemIndices[i] ?? 0) % 3],
  }));
  return { ...record, rank, formatName: format.name, waka, summary, items };
}

/** (ギルド, ユーザー, JST日付) で決定的に引く。 */
export function drawDailyFortune(guildId: string, userId: string, date: string): OmikujiFortune {
  const rng = seededRng(`omikuji-v4:${guildId}:${userId}:${date}`);
  return fortuneFromRecord(drawRecord(rng));
}

/** JST の日付文字列 (YYYY-MM-DD) を返す。 */
export function jstDateString(now: Date): string {
  return new Date(now.getTime() + 9 * 60 * 60 * 1000).toISOString().slice(0, 10);
}

